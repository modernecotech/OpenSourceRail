def _coast_time(m,c,q,high,low,linear=0.):
    if high==low:return 0.
    if q==0:
        return m*(high-low)/c
    disc=4*q*c-linear*linear
    if disc>0:
        k=sqrt(disc)
        return 2*m/k*(atan((2*q*high+linear)/k)-atan((2*q*low+linear)/k))
    if abs(disc)<1e-20:
        return 2*m*(1/(2*q*low+linear)-1/(2*q*high+linear))
    k=sqrt(-disc)
    def primitive(v):
        z=2*q*v+linear
        return log((z-k)/(z+k))/k
    return m*(primitive(high)-primitive(low))


def _coast_distance(m,c,q,high,low,linear=0.):
    if high==low:return 0.
    if q==0:return m*(high*high-low*low)/(2*c)
    resistance=lambda v:c+linear*v+q*v*v
    return m/(2*q)*log(resistance(high)/resistance(low))-linear/(2*q)*_coast_time(m,c,q,high,low,linear)


def profile(distance_m, mass_kg_per_car, *, speed_cap_m_s=20.,
            acceleration_m_s2=.4,service_deceleration_m_s2=.6,
            rolling_coefficient=.0025,bearing_drag_N_per_car=50.,
            quadratic_drag_N_per_car_per_m_s_squared=1.8,
            grade_fraction=0.,headwind_m_s=0.,cars=6,loading=None,rotating_equivalent_mass_kg_per_car=0.):
    """Solve accelerate–natural coast–brake to rest, respecting the speed cap.

    Powered acceleration and braking are net kinematic *targets*. The returned
    required forces must still be generated by an actual motor/brake system.
    Downhill cases needing distributed braking at the cap are explicitly failed.
    """
    nums=(distance_m,mass_kg_per_car,speed_cap_m_s,acceleration_m_s2,
          service_deceleration_m_s2,rolling_coefficient,bearing_drag_N_per_car,
          quadratic_drag_N_per_car_per_m_s_squared,grade_fraction,headwind_m_s,rotating_equivalent_mass_kg_per_car)
    if any(not isfinite(x) for x in nums) or min(nums[:5])<=0 or min(nums[5:8])<0 or headwind_m_s<0 or rotating_equivalent_mass_kg_per_car<0 or cars<1:
        raise ValueError('Positive finite route/mass/speed/acceleration; nonnegative drag required')
    physical_mass=mass_kg_per_car;m=physical_mass+rotating_equivalent_mass_kg_per_car;a=acceleration_m_s2;b=service_deceleration_m_s2;q=quadratic_drag_N_per_car_per_m_s_squared
    constant=rolling_coefficient*physical_mass*G+bearing_drag_N_per_car
    grade_force=physical_mass*G*grade_fraction;c=constant+grade_force+q*headwind_m_s**2
    linear=2*q*headwind_m_s
    cap=speed_cap_m_s
    inputs=dict(distance_m=distance_m,mass_kg_per_car=physical_mass,effective_inertial_mass_kg_per_car=m,
        rotating_equivalent_mass_kg_per_car=rotating_equivalent_mass_kg_per_car,speed_cap_m_s=cap,
        acceleration_m_s2=a,service_deceleration_m_s2=b,rolling_coefficient_hypothesis=rolling_coefficient,
        bearing_drag_N_per_car_hypothesis=bearing_drag_N_per_car,
        quadratic_drag_N_per_car_per_m_s_squared_hypothesis=q,
        grade_fraction_hypothesis=grade_fraction,headwind_m_s_hypothesis=headwind_m_s,cars=cars,loading=loading)
    v=dict(schema='osr-wheel-longitudinal-requirement/1',inputs=inputs,
        reachable=False,reason=None,runtime_s=None,peak_speed_m_s=None,
        arrival_speed_before_braking_m_s=None,launch_distance_m=None,
        coast_distance_m=None,braking_distance_m=None,
        launch_time_s=None,coast_time_s=None,braking_time_s=None,
        launch_mechanical_energy_J_per_car=None,receiving_mechanical_energy_J_per_car=None,
        peak_launch_force_N_per_car=None,peak_launch_power_W_per_car=None,
        constant_wheel_drag_N_per_car=constant,
        grade_force_N_per_car=grade_force,
        actual_traction_force_available_N=None,physical_journey_completed=False,
        evidence_maturity='analytical',numerical_validity='valid')
    if c+linear*cap+q*cap*cap<0:
        v['reason']='downhill_speed_cap_requires_distributed_braking'
        v['profile_id']=identity(v);return v
    peak=min(cap,sqrt(2*distance_m/(1/a+1/b)))
    xa=peak*peak/(2*a)
    if xa+peak*peak/(2*b)>=distance_m-1e-9:
        arrival=peak;xc=0.;xb=peak*peak/(2*b);tc=0.
    elif c==0 and q==0:
        arrival=peak;xb=peak*peak/(2*b);xc=distance_m-xa-xb;tc=xc/peak
    else:
        low=0. if c>0 else max(0.,(-linear+sqrt(linear*linear-4*q*c))/(2*q))*(1+1e-12)+1e-9
        maxdistance=xa+_coast_distance(m,c,q,peak,low,linear)+low*low/(2*b)
        if distance_m>maxdistance+1e-8:
            v['reason']='coast_stops_before_receiving_zone'
            v['maximum_flat_coast_reach_m']=maxdistance
            v['profile_id']=identity(v);return v
        hi=peak
        for _ in range(80):
            mid=(low+hi)/2
            covered=xa+_coast_distance(m,c,q,peak,mid,linear)+mid*mid/(2*b)
            # Covered decreases as receiving speed increases, provided natural
            # deceleration is below requested service braking. Verify below.
            if covered>distance_m:low=mid
            else:hi=mid
        arrival=(low+hi)/2
        xb=arrival*arrival/(2*b);xc=distance_m-xa-xb
        tc=_coast_time(m,c,q,peak,arrival,linear)
    # If natural resistance alone exceeds requested net brake deceleration, the
    # requested phase needs forward traction and isn't a receiving-brake case.
    if max(c,c+linear*arrival+q*arrival*arrival)>=m*b:
        v['reason']='natural_deceleration_exceeds_service_brake_target'
        v['profile_id']=identity(v);return v
    ta=peak/a;tb=arrival/b
    launch_ke=.5*m*peak*peak
    launch_work=launch_ke+c*xa+linear*peak**3/(3*a)+q*peak**4/(4*a)
    receive_ke=.5*m*arrival*arrival
    brake_work=receive_ke-c*xb-linear*arrival**3/(3*b)-q*arrival**4/(4*b)
    # Exact energy accounting by phase. Coast work is its kinetic energy loss;
    # subtract grade potential to isolate nonnegative dissipative resistance.
    grade_work=grade_force*distance_m
    dissipated=launch_work-brake_work-grade_work
    max_force=m*a+c+linear*peak+q*peak*peak
    result=dict(reachable=True,reason='kinematic_targets_require_actual_drive_and_brake_maps',
        runtime_s=ta+tc+tb,peak_speed_m_s=peak,
        arrival_speed_before_braking_m_s=arrival,launch_distance_m=xa,
        coast_distance_m=xc,braking_distance_m=xb,
        launch_time_s=ta,coast_time_s=tc,braking_time_s=tb,
        launch_mechanical_energy_J_per_car=launch_work,
        receiving_mechanical_energy_J_per_car=brake_work,
        peak_launch_force_N_per_car=max_force,
        peak_launch_power_W_per_car=max_force*peak,
        peak_receiving_brake_force_N_per_car=m*b-c,
        peak_receiving_brake_power_W_per_car=max(0.,(m*b-c-linear*arrival-q*arrival*arrival)*arrival),
        launch_mechanical_energy_kWh_train=launch_work*cars/3.6e6,
        receiving_mechanical_energy_kWh_train=brake_work*cars/3.6e6,
        rolling_bearing_aerodynamic_dissipation_J_per_car=dissipated,
        grade_potential_energy_J_per_car=grade_work,
        longitudinal_energy_residual_J_per_car=launch_work-brake_work-dissipated-grade_work,
        phase_distance_residual_m=distance_m-xa-xc-xb,
        independent_friction_braking_assumed=True,
        longitudinal_braking_resistance_credit=False)
    v.update(result);v['profile_id']=identity(v);return v


def station_zone(p, length_m, *, train_length_m=104.5,dwell_s=35.,headway_s=120.,
                 section_length_m=12.5,secondary_length_m=9.,car_length_m=17.,
                 independent_train_phase_branches=2):
    """Full-train engagement geometry and conservative berth resource screen.

    The powered interval has receipt on approach and launch beyond the berth.
    At departure the last passive fin must remain wholly inside launch stators;
    at receipt the first fin enters before braking begins. The 4m setback of
    each9m fin on a17m car is counted. Consecutive trains need independent phase
    branches; one exclusive winding cannot provide this service.
    """
    if min(length_m,train_length_m,section_length_m,headway_s)<=0 or dwell_s<0:
        raise ValueError('Invalid station dimensions/timing')
    if not p['reachable']:
        return dict(length_m=length_m,geometry_full_engagement=False,
            required_shared_winding_m=None,launch_zone_m=None,receiving_zone_m=None,
            sections_per_direction=ceil(length_m/section_length_m),
            nominal_resource_interval_s=None,nominal_resource_screen='fail',
            reason='unreachable longitudinal proposal',station_id=identity([p['profile_id'],length_m]))
    offset=(car_length_m-secondary_length_m)/2
    # Outgoing length measured from platform-train leading nose at departure.
    # Complete fin remains energized through prescribed target acceleration.
    out=p['launch_distance_m']-offset
    approach=p['braking_distance_m']+train_length_m-offset
    required=out+approach
    # A following train occupies the same berth when the outgoing train's rear
    # clears it. This conservative sum keeps receipt, dwell and clearance serial.
    clear=sqrt(2*train_length_m/p['inputs']['acceleration_m_s2'])
    resource=p['braking_time_s']+dwell_s+clear
    full=length_m+1e-9>=required
    value=dict(schema='osr-wheel-station-resource/1',profile_id=p['profile_id'],
        length_m=length_m,geometry_full_engagement=full,
        required_shared_winding_m=required,launch_zone_m=out,
        receiving_zone_m=approach,passive_secondary_length_m=secondary_length_m,
        first_fin_setback_from_nose_m=offset,
        sections_per_direction=ceil(length_m/section_length_m),section_length_m=section_length_m,
        minimum_independent_train_phase_branches_per_direction=independent_train_phase_branches,
        nominal_resource_interval_s=resource,
        nominal_resource_screen='pass' if full and resource<=headway_s and independent_train_phase_branches>=2 else 'fail',
        physical_headway_qualified=False,section_handoff_qualified=False,
        protection_brake_envelope_qualified=False,
        train_berth_clear_time_s=clear,
        station_drive_thrust_current_voltage_thermal_screen='unknown')
    value['station_id']=identity(value);return value


def brake_bound(speed_m_s=20., *, adhesion_coefficient=.05,downhill_grade_fraction=.02,
                reaction_s=1.,target_deceleration_m_s2=.6):
    """Wheel friction-only wet/downhill stopping requirement, no drag credit."""
    if speed_m_s<0 or adhesion_coefficient<0 or downhill_grade_fraction<0 or reaction_s<0:
        raise ValueError('Positive speed, adhesion, downhill and reaction required')
    delivered=min(target_deceleration_m_s2,adhesion_coefficient*G)
    net=delivered-G*downhill_grade_fraction
    stopping= speed_m_s*reaction_s+speed_m_s**2/(2*net) if net>0 else None
    return dict(speed_m_s=speed_m_s,adhesion_coefficient_hypothesis=adhesion_coefficient,
        downhill_grade_fraction=downhill_grade_fraction,reaction_s_hypothesis=reaction_s,
        target_deceleration_m_s2=target_deceleration_m_s2,
        adhesion_limited_level_deceleration_m_s2=delivered,
        net_downhill_deceleration_m_s2=net,stopping_distance_m=stopping,
        necessary_stop_screen='pass' if stopping is not None else 'fail',
        brake_supplier_curve_and_WSP_verified=False,
        no_regenerative_brake_credit=True,no_aerodynamic_or_rolling_drag_credit=True)


def evaluate(vehicle, root=ROOT):
    from . import electrical
    config=brief(root);sv=config['service'];vc=config['vehicle'];m=vehicle['mass']
    from .braking import rotating_stock
    rotors=rotating_stock(vehicle);rot=rotors['equivalent_inertial_mass_kg_per_car']
    masses=dict(empty=m['accounted_tare_kg_per_car'],normal=m['accounted_cap_loaded_kg_per_car'],
                crowd_control=m['accounted_160_control_kg_per_car'])
    profiles=[]
    for distance in sv['prototype_distances_m']:
        for loading,mass in masses.items():
            profiles.append(profile(distance,mass,cars=vc['cars'],loading=loading,rotating_equivalent_mass_kg_per_car=rot))
    chosen=next(p for p in profiles if p['inputs']['distance_m']==2000 and p['inputs']['loading']=='normal')
    zones=[station_zone(chosen,length) for length in sv['station_winding_library_m']]
    survivors=[z for z in zones if z['nominal_resource_screen']=='pass']
    selected=min(survivors,key=lambda z:z['length_m']) if survivors else None
    sensitivity=[profile(d,masses['normal'],rolling_coefficient=rr,grade_fraction=gr,
                        loading='normal',rotating_equivalent_mass_kg_per_car=rot)
        for d in (1500.,2000.) for rr in (.001,.0025,.005) for gr in (-.02,-.01,0.,.01,.02)]
    longest_distance=2999.9312214890124
    longest=[profile(longest_distance,mass,grade_fraction=grade,headwind_m_s=wind,loading=loading,rotating_equivalent_mass_kg_per_car=rot)
             for loading,mass in masses.items() for grade in (0.,.01,.02,-.01) for wind in (0.,10.)]
    longest_source='cities/catalogue/south-asia/Pakistan/Faisalabad/engineering/maglev/summary.json'
    from pathlib import Path
    from .common import digest
    if digest(Path(root)/longest_source)!='cfa684ad551e9b4a9a1d63fbf95698eca0a8552300fec450abaee796bc56a30a':
        raise ValueError('Retained longest-gap metadata source differs')
    environment=[]
    for d in (1500.,2000.):
        for loading,mass in masses.items():
            for grade in (0.,.01,.02,-.01):
                for wind in (0.,10.):
                    pp=profile(d,mass,grade_fraction=grade,headwind_m_s=wind,loading=loading)
                    environment.append(dict(profile=pp,reference_hotel_energy=None if not pp['reachable'] else
                        electrical.charge_leg(pp['runtime_s'],root=root),
                        adverse_hotel_energy=None if not pp['reachable'] else
                        electrical.charge_leg(pp['runtime_s'],hotel_kW=50.,module_environment_C=50.,root=root),
                        physical_journey_completed=False))
    brakes=[brake_bound(adhesion_coefficient=mu,downhill_grade_fraction=gr)
            for mu in (.03,.05,.1,.15) for gr in (0.,.01,.02,.04)]
    from . import electrical
    e=electrical.evaluate(vehicle,profiles,root)
    from .native_drive import conditional_map
    drive_bounds=conditional_map(chosen['peak_launch_force_N_per_car'],
        length_m=config['propulsion']['secondary_length_m'],
        height_m=config['propulsion']['secondary_height_m'],
        thickness_m=config['propulsion']['secondary_thickness_m'],
        airgap_each_side_m=config['propulsion']['primary_target_airgap_each_side_m'])
    critical_heat=chosen['receiving_mechanical_energy_J_per_car']
    result=dict(schema='osr-wheel-operations-evaluation/1',**{k:vehicle[k] for k in IDS},
        profiles=profiles,rotating_stock=rotors,reference_environment_cases=environment,longest_retained_gap_cases=longest,
        longest_retained_gap_context=dict(distance_m=longest_distance,city='Faisalabad',line='line-2',
            from_stop='line-2-operating-0005',to_stop='line-2-operating-0006',adjacent_gaps_scanned=17268,
            source_role='Geography only; old maglev performance is not reused'),
        selected_scenario=dict(profile=chosen,inputs=chosen['inputs']),
        selected_station=selected,station_options=zones,grade_and_rolling_sensitivity=sensitivity,
        brake_envelopes=brakes,electrical=e,station_drive_bound_map=drive_bounds,
        service=dict(cars=6,passengers_per_car=46,headway_s=120.,dwell_s=35.,
            normal_capacity_pphpd_arithmetic=8280.,launch_speed_cap_m_s=20.,
            physical_headway_qualified=False),
        friction_brake_duty=dict(receiving_energy_J_per_car=critical_heat,
            train_receiving_energy_kWh=critical_heat*6/3.6e6,
            brake_discs_per_car_reference=8,
            equal_disc_energy_J=critical_heat/8,
            thermal_capacity_and_repeated_duty_screen='unknown',
            scope='All planned receiving work assigned to independent wheel friction brakes until an actual station receiving motor map exists; no assumed regeneration.'),
        faults=[
            dict(fault='station launch power lost',response='Retain wheel brake at berth; do not depart',execution='analytical response requirement'),
            dict(fault='receiving motor power lost',response='Independent friction brake required; use wet/downhill stopping authority',execution='analytical requirement, brake/WSP hardware not qualified'),
            dict(fault='off-zone stop',response='No onboard drive. Dispatch rail-compatible rescue/tow vehicle and protected evacuation if necessary.',restart_available=False,rescue_response_time_s=None),
            dict(fault='service supply lost',response='Preserve independently fused essential branch and braking reserve; HVAC degradation and evacuation need hot-weather validation',execution='not physically demonstrated'),
        ],
        budget=dict(prototype_profiles=len(profiles),station_geometry_options=len(zones),
            grade_rolling_cases=len(sensitivity),independent_braking_cases=len(brakes),
            service_battery_alternatives=2,secondary_slip_cases=5,longest_gap_cases=len(longest),conditional_drive_cases=len(drive_bounds['cases']),reference_environment_cases=len(environment)),
        source_sha256={**source_map(root,PRODUCERS),**e['source_sha256'],longest_source:digest(Path(root)/longest_source)},**FLAGS)
    result['evaluation_id']=identity(result);return result
