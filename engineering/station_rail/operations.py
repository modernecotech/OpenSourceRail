"""Deterministic wheelrail station-launch requirements, never available thrust.

SI longitudinal point-mass phases with finite station engagement geometry.
Natural coasting uses R = c_rr*m*g + bearing + q*v²; grade is separate potential
energy and contributes to longitudinal resistance. No powered boosters are
silently inserted. Lateral wheel/rail dynamics and adhesion remain qualification
requirements.
"""
from __future__ import annotations
