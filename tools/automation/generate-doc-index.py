#!/usr/bin/env python3
"""Generate a central index of Markdown documentation files."""

from __future__ import annotations

import subprocess
import argparse
from collections import defaultdict
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[2]
OUT = REPO_ROOT / "docs" / "INDEX.md"
SKIP_PARTS = {
    ".git",
    ".mypy_cache",
    ".pytest_cache",
    ".ruff_cache",
    ".venv",
    "node_modules",
    "target",
}
EXCLUDED_DOCS = {
    "engineering/ferrite_maglev/README.md",
    "engineering/ferrite_maglev/city-index.md",
    "docs/design-engine/ferrite-maglev/pilot-delivery/README.md",
    "docs/design-engine/ferrite-maglev/capability-migration/README.md",
    "docs/releases/v0.5.1.md",
    "docs/releases/v0.5.2.md",
}


def _indexed(path: Path) -> bool:
    name = path.as_posix()
    if not SKIP_PARTS.isdisjoint(path.parts) or not (REPO_ROOT / path).exists():
        return False
    if name.startswith(("legacy/", "docs/archives/", "docs/design-engine/ferrite-maglev/")):
        return False
    if name.startswith("cities/catalogue/") and name != "cities/catalogue/README.md":
        return False
    return name not in EXCLUDED_DOCS


def _git_markdown_files() -> list[Path]:
    tracked = subprocess.check_output(
        ["git", "ls-files", "*.md"],
        cwd=REPO_ROOT,
        text=True,
    ).splitlines()
    untracked = subprocess.check_output(
        ["git", "ls-files", "--others", "--exclude-standard", "*.md"],
        cwd=REPO_ROOT,
        text=True,
    ).splitlines()
    paths = sorted({Path(p) for p in tracked + untracked})
    return [
        p for p in paths if _indexed(p)
    ]


def _title(path: Path) -> str:
    try:
        for line in (REPO_ROOT / path).read_text(encoding="utf-8").splitlines():
            if line.startswith("# "):
                return line[2:].strip()
    except UnicodeDecodeError:
        pass
    if path.name == "README.md":
        return path.parent.name or "Repository README"
    return path.stem.replace("-", " ").replace("_", " ").title()


def _section(path: Path) -> str:
    if len(path.parts) == 1:
        return "Repository Root"
    return path.parts[0]


def _link(path: Path) -> str:
    return Path("..", path).as_posix()


def generate() -> str:
    grouped: dict[str, list[Path]] = defaultdict(list)
    for path in _git_markdown_files():
        grouped[_section(path)].append(path)

    lines = [
        "# Maintained Documentation Index",
        "",
        "This file is generated by `tools/automation/generate-doc-index.py`.",
        "It indexes the current project entrypoints, engineering guidance, setup",
        "instructions and maintained implementation guides. Use the root",
        "[`README.md`](../README.md) for project navigation and the source map.",
        "",
        "Regenerate from the repository root with:",
        "",
        "```bash",
        "python3 tools/automation/generate-doc-index.py",
        "```",
        "",
    ]

    total = sum(len(paths) for paths in grouped.values())
    lines.extend(
        [
            f"Indexed Markdown files: **{total}**.",
            "",
            "## Sections",
            "",
            "| Section | Files |",
            "|---|---:|",
        ]
    )
    for section in sorted(grouped):
        anchor = section.lower().replace(" ", "-")
        lines.append(f"| [{section}](#{anchor}) | {len(grouped[section])} |")

    for section in sorted(grouped):
        lines.extend(["", f"## {section}", "", "| File | Title |", "|---|---|"])
        for path in grouped[section]:
            lines.append(f"| [`{path.as_posix()}`]({_link(path)}) | {_title(path)} |")

    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args()
    value = generate()
    if args.check:
        if not OUT.is_file() or OUT.read_text()!=value:
            print('stale: docs/INDEX.md')
            return 1
        print('current: docs/INDEX.md')
        return 0
    OUT.write_text(value, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
