#!/usr/bin/env python3
"""Generate or check the retained capability and source directory."""

import argparse, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from engineering.design_engine.capabilities import build, render

p = argparse.ArgumentParser(description=__doc__)
p.add_argument("--output", type=Path, default=ROOT / "docs/capabilities")
p.add_argument("--check", action="store_true")
a = p.parse_args()
data = build()
files = {
    "ledger.json": json.dumps(data, indent=2, sort_keys=True) + "\n",
    "directory.md": render(data),
    "README.md": "# Capability Directory\n\nGenerated by `./osr capabilities`.\n\n[Browse entry points](directory.md) or inspect the [source/contract/test ledger](ledger.json).\n\nThe six task areas retain all 25 previous routes and native owners. Appointed people and independent acceptance remain separate; unmapped focused tests are visible.\n",
}
for name, text in files.items():
    path = a.output / name
    if a.check:
        if not path.is_file() or path.read_text() != text:
            raise SystemExit("stale capability directory: " + name)
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
print(data["inventory"])
